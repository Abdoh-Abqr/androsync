"""The program's icon, in the sizes the desktop needs (Phase U). The files are generated from ``assets/androsync.svg`` (and
regenerated by ``branding/apply_logo.py`` whenever the logo changes)."""

from __future__ import annotations

import importlib.resources

#: Pixel sizes of the packaged PNG icons.
ICON_SIZES = (48, 128, 256)


def icon_png(size: int) -> bytes:
    """The PNG icon of ``size`` pixels (one of :data:`ICON_SIZES`)."""
    return importlib.resources.files("androsync").joinpath("assets", f"androsync-{size}.png").read_bytes()


def icon_svg() -> str:
    return importlib.resources.files("androsync").joinpath("assets", "androsync.svg").read_text(encoding="utf-8")
